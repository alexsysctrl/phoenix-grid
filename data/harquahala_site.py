HERE = Path(__file__).resolve().parent
SOURCE = HERE / "source-harquahala-sun-project-page.html"

WS = re.compile(r"\s+")
TAGS = re.compile(r"<[^>]+>")
FOLD = {ord(k): v for k, v in {"\u2019": "'", "\u2018": "'", "\u201c": '"', "\u201d": '"',
                               "\u00a0": " ", "\u2013": "-", "\u2014": "-"}.items()}


def page_text(path: Path = SOURCE) -> str:
    raw = unescape(path.read_text(encoding="utf-8", errors="ignore"))
    raw = TAGS.sub(" ", raw)
    text = WS.sub(" ", raw.translate(FOLD)).strip()
    # a link inside a sentence leaves a space before its punctuation once the tag is gone; the source has none
    return re.sub(r"\s+([.,;:])", r"\1", text)


def locate(text: str, phrase: str) -> str:
    target = WS.sub(" ", phrase).strip().lower()
    at = text.lower().find(target)
    if at < 0:
        raise LookupError(f"not on the filed project page: {phrase!r}")
    return text[at: at + len(target)]


