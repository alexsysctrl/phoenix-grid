def build(text: str) -> dict:
    rows = []
    for c in CLAIMS:
        rows.append({**c, "verbatim": locate(text, c["quote"])})
    return {
        "source": {
            "title": "Harquahala Sun (Copia Power) — project page: permitting and project description",
            "url": "https://harquahalasun.com",
            "read_on": "2026-10-28",
            "kept_as": SOURCE.name,
            "nature": "an applicant's own site: the decision numbers and county case numbers are citations to public records, the dollar figures are the applicant's estimates",
        },
        "claims": rows,
        "record_identifiers_found": {d: (d in text) for d in DECISION_IDS},
        "checkable_next": [
            "Arizona Corporation Commission Decision 78590 (21 June 2022), 78850 (25 January 2023), 79467 (13 August 2024)",
            "Maricopa County CPA250002 / ZC Z250015 and their approvals",
            "The outcome of LS Case No. 248 (docket L-21304A-25-0169-00248)",
        ],
    }


def selftest() -> None:
    text = page_text()
    # known-true: the decision numbers this file is about must be present, and the pattern must not invent one.
    for d in DECISION_IDS:
        assert d in text, f"{d} is cited in this document and the extracted text does not contain it"
    # a located span is the phrase, not a window around it: if it were wider, every citation here would be sloppy
    assert locate(text, "Decision 78590") == "Decision 78590", "the located span is wider than the phrase"
    # known-false: a decision this page does not claim must not be found
    for phrase in ("Decision 80001", "the Committee denied the application", "L-21304A-25-0169-00999"):
        try:
            locate(text, phrase)
        except LookupError:
            continue
        raise AssertionError(f"the extractor found something this page does not say: {phrase!r}")
    out = build(text)
    assert len(out["claims"]) == len(CLAIMS), "a claim dropped out"
    assert all(r["verbatim"] for r in out["claims"]), "a claim resolved to an empty span"
    approved = [r for r in out["claims"] if "approved" in r["claim"]]
    assert len(approved) == 3, "this page documents three approvals; if that changed, the reading changed"
    assert all("Decision 7" in r["verbatim"] for r in approved), "an approval row lacks its decision number"
    print(f"self-test passed: {len(CLAIMS)} claims located on the filed page, {len(DECISION_IDS)} public record "
          f"identifiers confirmed present, three approvals each carrying its Commission decision number, and three "
          "phrases this page does not contain correctly rejected")


